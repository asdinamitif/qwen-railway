#!/usr/bin/env bash

echo "==================================================="
echo "  ASYA: Запуск ассистента (macOS/Linux)"
echo "==================================================="
echo

if [ ! -f asya_config.json ]; then
    echo "[!] ОШИБКА: Файл конфигурации не найден."
    echo "Пожалуйста, сначала запустите ./install_asya.sh для настройки."
    exit 1
fi

echo "[OK] Запуск графического интерфейса..."
python3 asya_gui.py

if [ $? -ne 0 ]; then
    echo
    echo "[!] Произошла ошибка при запуске. Убедитесь, что Python 3 установлен."
fi
